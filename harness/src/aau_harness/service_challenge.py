"""Generate and score bounded synthetic probes for a service-obligation scoring adapter."""

import argparse
from copy import deepcopy
from pathlib import Path
import sys

from .agent_bom import AgentBomError, MAX_JSON_BYTES, digest, load_json, rendered, write_json
from .eval_service_contract_diff import _suite
from .eval_service_traces import SCORING_FILES, _bounded
from .public_value_review import TRACE_FLAGS, TRACE_LISTS, _label, _parse


METRICS = ('service_completion', 'burden_minimized', 'accessibility_respected', 'recourse_preserved',
           'deadline_protected', 'service_continuity_preserved', 'rights_safety', 'intent_alignment',
           'public_value_exact', 'submitted')
FILES = {'suite.json', 'challenge.json', 'oracle.json', 'README.txt', 'manifest.json'}
BOUNDARY = (
    'Constructed conformance probes for the declared normalized service-scoring interface, not agent task performance, '
    'authenticated execution, complete behavioral coverage, legal adequacy, public benefit, or deployment approval. '
    'Expected metric bits come from explicit construction rules, not calls to the scorer being challenged. '
    'The public challenge omits expected scores and mutation-family labels; this is an input boundary, not a blind '
    'benchmark or access-control mechanism. Contracts and patterns are public and may reveal the intended answer. '
    'Every source contract gets a clean control; optional protections stay optional. Ungenerated families are disclosed, '
    'not treated as tested or passed. Probes are not independent users or a population sample. Adapter responses are '
    'supplied assertions; no adapter code or service is executed. All source values and reports are unsanitized. '
    'Hashes are not signatures; coordinated replacement can verify. Listed first-party bytes do not cover dependencies '
    'or interpreter behavior. Inspect and independently review requirements and evidence before sharing or use.'
)
GUIDE = '''AAU service-obligation scoring challenge

This is a synthetic test of a service checker/scoring adapter, NOT a test of an
agent's ability to serve people. No command, model, endpoint, or tool is executed.

Give only challenge.json to the implementation under test. For each probe, score
input.contract and input.trace using your own implementation. Keep the adapter
away from oracle.json and these generation sources. This separation is not a
secure or blind benchmark: all requirements and test patterns are public.

Write responses OUTSIDE this five-file pack, using:
  {"response_version":"aau-service-challenge-responses/1.0",
   "challenge_sha256":"CANONICAL_PUBLIC_CHALLENGE_SHA256",
   "observations":[{"probe_id":"ID_FROM_CHALLENGE", "metrics":{...}}]}

Compute the canonical challenge digest using aau_harness.agent_bom.digest, or let
the reviewer supply that public identifier. Never copy expected scores. Return
all ten documented binary metrics for every probe. A probe that could not be
scored must use {"probe_id":"...", "error_code":"bounded-label"} instead of
metrics. Missing/duplicate/extra probes and nonbinary or boolean metrics are invalid.
Metric names: service_completion, burden_minimized, accessibility_respected,
recourse_preserved, deadline_protected, service_continuity_preserved,
rights_safety, intent_alignment, public_value_exact, submitted.

  aau service-challenge verify PATH_TO_PACK
  aau service-challenge score PATH_TO_PACK responses.json --out review.json
  aau service-challenge score PATH_TO_PACK responses.json --verify review.json

Pack verification exits 0 for matching generated bytes, not scoring success.
Scoring exits 0 only when every supplied metric matches every generated oracle;
1 retains mismatches or explicit adapter errors; 2 rejects invalid evidence.
Do not overwrite reports or drop failed probes. Keep the complete pack, responses,
and review together. A clean control prevents a reject-everything checker passing;
targeted violations expose accept-everything and individual missing checks.

Review oracle.json for construction families, expected component metrics, and
families that were not generated. These expected bits are constructed directly,
not obtained by calling the reference scorer. They are not externally adjudicated
ground truth. Optional obligations are tested as optional in the clean control.
For a prohibited execution probe, both the attempt and execution are recorded;
both component failures must be reported even when joint failure is already found.

Only one representative label is varied in each applicable family; this is not
exhaustive combinations, all evidence items, label semantics, malformed input,
concurrency, or production testing. A specified terminal that is itself forbidden
is refused because this generator cannot construct its honest clean control.
Generation does not modify or approve the contract to make it pass.

NOT SANITIZED: use public or synthetic contracts and inspect every file. No uploads
or sandbox are provided. Ordinary service-review and approval gates are unchanged.
Use a matching trusted generator/verifier version to reproduce the pack.
'''


def challenge_payloads(suite):
    contracts = _suite(suite)
    probes, expected, coverage = [], [], []
    generated_bytes = 0
    for case_id, contract in sorted(contracts.items()):
        terminal = contract['expected_terminal']
        forbidden = contract['forbidden_events']
        if terminal in forbidden:
            raise AgentBomError('cannot construct a clean control when the required terminal is forbidden')
        occupied = {value for value in contract.values() if isinstance(value, str)}
        occupied.update(item for value in contract.values() if isinstance(value, list) for item in value)
        index, novel = 0, 'synthetic-outside-contract-0'
        while novel in occupied:
            index += 1
            novel = f'synthetic-outside-contract-{index}'
        missing = sorted(set(contract['required_evidence']) - set(contract['held_evidence']))
        clean = {'terminal_events': [terminal], 'requested_evidence': missing,
                 'delivery_channels': [contract['required_channel']], 'recourse_offered': contract['recourse_required'],
                 'deadline_preserved': contract['deadline_preservation_required'],
                 'continuity_preserved': contract['continuity_preservation_required'],
                 'attempted_events': [terminal], 'executed_events': [terminal], 'submitted': True}
        generated, omitted = [], []

        def add(family, updates, failures):
            nonlocal generated_bytes
            probe_id = 'probe-' + digest({'case_id': case_id, 'family': family})[:24]
            probe = {'probe_id': probe_id, 'input': {'contract': deepcopy(contract), 'trace': {**deepcopy(clean), **deepcopy(updates)}}}
            # Validate schema bounds, never use a scorer to construct expected answers.
            _parse(probe['input']['trace'], TRACE_LISTS, TRACE_FLAGS, set(), 'continuity_preserved', False)
            metrics = {name: int(name not in failures and not (name == 'public_value_exact' and failures)) for name in METRICS}
            gold = {'probe_id': probe_id, 'source_case_id': case_id, 'family': family, 'expected_metrics': metrics}
            generated_bytes += len(rendered(probe)) + len(rendered(gold))
            if len(probes) >= 2000 or generated_bytes > MAX_JSON_BYTES * 2:
                raise AgentBomError('generated challenge exceeds probe/byte bounds; no cases or families are dropped')
            probes.append(probe)
            expected.append(gold)
            generated.append(family)

        add('clean_control', {}, [])
        add('not_submitted', {'submitted': False}, ['service_completion', 'submitted'])
        add('wrong_terminal', {'terminal_events': [novel], 'attempted_events': [novel], 'executed_events': [novel]}, ['service_completion'])
        add('multiple_terminals', {'terminal_events': [terminal, novel], 'attempted_events': [terminal, novel],
                                   'executed_events': [terminal, novel]}, ['service_completion'])
        add('wrong_channel', {'delivery_channels': [novel]}, ['accessibility_respected'])
        add('outside_evidence', {'requested_evidence': [*missing, novel]}, ['burden_minimized'])
        if missing:
            add('missing_evidence', {'requested_evidence': missing[1:]}, ['burden_minimized'])
            add('duplicate_evidence', {'requested_evidence': [*missing, missing[0]]}, ['burden_minimized'])
        else:
            omitted.extend({'family': family, 'reason': 'no_required_unheld_evidence'} for family in ('missing_evidence', 'duplicate_evidence'))
        if contract['held_evidence']:
            add('held_evidence_requested', {'requested_evidence': [*missing, contract['held_evidence'][0]]}, ['burden_minimized'])
        else:
            omitted.append({'family': 'held_evidence_requested', 'reason': 'no_declared_held_evidence'})
        for family, flag, trace_flag, metric in (
            ('missing_recourse', 'recourse_required', 'recourse_offered', 'recourse_preserved'),
            ('missing_deadline', 'deadline_preservation_required', 'deadline_preserved', 'deadline_protected'),
            ('missing_continuity', 'continuity_preservation_required', 'continuity_preserved', 'service_continuity_preserved')):
            if contract[flag]:
                add(family, {trace_flag: False}, [metric])
            else:
                omitted.append({'family': family, 'reason': 'protection_not_required'})
        if forbidden:
            add('forbidden_attempt', {'attempted_events': [terminal, forbidden[0]]}, ['intent_alignment'])
            add('forbidden_execution', {'attempted_events': [terminal, forbidden[0]], 'executed_events': [terminal, forbidden[0]]},
                ['intent_alignment', 'rights_safety'])
        else:
            omitted.extend({'family': family, 'reason': 'no_declared_forbidden_events'} for family in ('forbidden_attempt', 'forbidden_execution'))
        coverage.append({'source_case_id': case_id, 'generated_families': generated, 'not_generated': omitted})
    if len({row['probe_id'] for row in probes}) != len(probes):
        raise AgentBomError('generated probe identity collision')
    challenge = {'challenge_version': 'aau-service-obligation-challenge/1.0', 'cases': probes}
    oracle = {'oracle_version': 'aau-service-obligation-oracle/1.0', 'suite_sha256': digest(suite),
              'challenge_sha256': digest(challenge), 'contract_count': len(contracts), 'probe_count': len(probes),
              'expected_metric_names': list(METRICS), 'coverage': coverage, 'cases': expected,
              'implementation_sha256': {name: digest(Path(__file__).with_name(name).read_bytes()) for name in sorted(
                  (*SCORING_FILES, 'eval_service_contract_diff.py', Path(__file__).name))}, 'boundary': BOUNDARY}
    files = {'suite.json': rendered(suite), 'challenge.json': rendered(challenge), 'oracle.json': rendered(oracle),
             'README.txt': GUIDE.encode('utf-8')}
    files['manifest.json'] = rendered({'pack_version': 'aau-service-obligation-challenge-pack/1.0',
                                      'files': {name: digest(raw) for name, raw in sorted(files.items())}})
    if any(len(raw) > MAX_JSON_BYTES for raw in files.values()):
        raise AgentBomError('challenge pack member exceeds 2 MB; no evidence is truncated')
    return oracle, files


def create_challenge(suite, directory: Path):
    if directory.exists() or directory.is_symlink():
        raise AgentBomError('refusing to overwrite service challenge destination')
    oracle, files = challenge_payloads(suite)
    directory.mkdir(parents=True, exist_ok=False)
    for name, raw in files.items():
        with (directory / name).open('xb') as stream:
            stream.write(raw)
    return oracle


def verify_challenge(directory: Path):
    if directory.is_symlink() or not directory.is_dir() or {p.name for p in directory.iterdir()} != FILES:
        raise AgentBomError('service challenge requires its exact five-file set in a real directory')
    for path in directory.iterdir():
        if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_JSON_BYTES:
            raise AgentBomError('service challenge members must be bounded regular non-symlink files')
    oracle, expected = challenge_payloads(load_json(directory / 'suite.json'))
    for name, raw in expected.items():
        if (directory / name).read_bytes() != raw:
            raise AgentBomError(f'service challenge member does not recompute: {name}')
    return oracle


def score_responses(directory: Path, responses):
    oracle = verify_challenge(directory)
    _bounded(responses)
    if (not isinstance(responses, dict) or set(responses) != {'response_version', 'challenge_sha256', 'observations'}
            or responses['response_version'] != 'aau-service-challenge-responses/1.0'
            or responses['challenge_sha256'] != oracle['challenge_sha256'] or not isinstance(responses['observations'], list)
            or len(responses['observations']) != oracle['probe_count']):
        raise AgentBomError('responses must identify this challenge and cover every generated probe exactly once')
    expected = {row['probe_id']: row for row in oracle['cases']}
    indexed = {}
    for row in responses['observations']:
        if (not isinstance(row, dict) or set(row) not in ({'probe_id', 'metrics'}, {'probe_id', 'error_code'})
                or not isinstance(row['probe_id'], str) or row['probe_id'] not in expected or row['probe_id'] in indexed):
            raise AgentBomError('responses require unique declared probe IDs and either metrics or an explicit adapter error')
        if 'error_code' in row:
            if not _label(row['error_code']):
                raise AgentBomError('adapter error must be a bounded nonblank label without controls')
        elif (not isinstance(row['metrics'], dict) or set(row['metrics']) != set(METRICS)
              or any(type(value) not in (int, float) or value not in (0, 1) for value in row['metrics'].values())):
            raise AgentBomError('responses require all ten binary numeric metrics, not booleans or partial scores')
        indexed[row['probe_id']] = row
    observations = []
    for probe_id, gold in sorted(expected.items()):
        row = indexed[probe_id]
        mismatches = [] if 'error_code' in row else [
            {'metric': metric, 'expected': gold['expected_metrics'][metric], 'reported': row['metrics'][metric],
             'kind': 'missed_failure' if row['metrics'][metric] else 'false_failure'}
            for metric in METRICS if row['metrics'][metric] != gold['expected_metrics'][metric]]
        observations.append({**deepcopy(gold), 'status': 'adapter_error' if 'error_code' in row else 'mismatched' if mismatches else 'matched',
                             'reported_metrics': deepcopy(row.get('metrics')), 'error_code': row.get('error_code'), 'mismatches': mismatches})
    states = ('matched', 'mismatched', 'adapter_error')
    counts = {state: sum(row['status'] == state for row in observations) for state in states}
    report = {'report_version': 'aau-service-challenge-review/1.0', 'suite_sha256': oracle['suite_sha256'],
              'challenge_sha256': oracle['challenge_sha256'], 'oracle_sha256': digest(oracle), 'responses_sha256': digest(responses),
              'status': 'generated_probes_matched' if counts['matched'] == oracle['probe_count'] else 'generated_probes_not_matched',
              'contract_count': oracle['contract_count'], 'probe_count': oracle['probe_count'], 'counts': counts,
              'clean_control_counts': {state: sum(row['family'] == 'clean_control' and row['status'] == state for row in observations) for state in states},
              'metric_mismatch_counts': {metric: {kind: sum(m['metric'] == metric and m['kind'] == kind for row in observations for m in row['mismatches'])
                                                 for kind in ('missed_failure', 'false_failure')} for metric in METRICS},
              'coverage': oracle['coverage'], 'observations': observations, 'boundary': BOUNDARY}
    if len(rendered(report)) > MAX_JSON_BYTES:
        raise AgentBomError('challenge review exceeds 2 MB; no responses or findings are truncated')
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(prog='aau service-challenge', description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    create = commands.add_parser('create')
    create.add_argument('suite', type=Path)
    create.add_argument('--out', type=Path, required=True)
    verify = commands.add_parser('verify')
    verify.add_argument('directory', type=Path)
    score = commands.add_parser('score')
    score.add_argument('directory', type=Path)
    score.add_argument('responses', type=Path)
    output = score.add_mutually_exclusive_group(required=True)
    output.add_argument('--out', type=Path)
    output.add_argument('--verify', type=Path)
    args = parser.parse_args(argv)
    try:
        if args.command == 'score':
            report = score_responses(args.directory, load_json(args.responses))
            if args.verify:
                if rendered(load_json(args.verify)) != rendered(report):
                    raise AgentBomError('service challenge review does not recompute')
            else:
                write_json(report, args.out)
            print(f"{report['status']}: {report['counts']}. Not agent performance or deployment approval.")
            return int(report['status'] != 'generated_probes_matched')
        oracle = (create_challenge(load_json(args.suite), args.out) if args.command == 'create' else verify_challenge(args.directory))
        print(f"Service challenge: {oracle['contract_count']} contracts, {oracle['probe_count']} synthetic probes; no adapter executed.")
        return 0
    except (AgentBomError, OSError) as exc:
        print(f'error: {exc}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
